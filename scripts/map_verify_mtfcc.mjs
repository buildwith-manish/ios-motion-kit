#!/usr/bin/env node
/**
 * Audits the city baker's MTFCC table against the Census Bureau's official list (run in CI: needs census.gov and
 * poppler's pdftotext).
 *   node scripts/map_verify_mtfcc.mjs [--year=2025]
 * Writes docs/map-verify-mtfcc.md. Exit 1 if a code that the baker DRAWS is missing from the official list, or an
 * official road / water / park code is missing from the table.
 */
import {execFileSync} from 'node:child_process';
import {mkdirSync, readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const year = (process.argv.find((a) => a.startsWith('--year=')) ?? '--year=2025').split('=')[1];
const url = `https://www2.census.gov/geo/pdfs/reference/mtfccs${year}.pdf`;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let pdf;
for (let a = 0; !pdf; a++) {
  try {
    const r = await fetch(url);
    if (!r.ok) throw new Error(`HTTP ${r.status}`);
    pdf = Buffer.from(await r.arrayBuffer());
  } catch (e) { if (a >= 4) throw new Error(`${url}: ${e.message}`); await sleep(1000 * 2 ** a); }
}
const dir = join(ROOT, '.cache', 'verify');
mkdirSync(dir, {recursive: true});
writeFileSync(join(dir, 'mtfcc.pdf'), pdf);
const text = execFileSync('pdftotext', ['-layout', join(dir, 'mtfcc.pdf'), '-'], {encoding: 'utf8'});
// a table row starts with the code, then the feature class name, then column gap
const official = new Map();
for (const line of text.split('\n')) {
  const m = /^\s*([A-Z]\d{4})\s+(.+?)(?:\s{2,}|$)/.exec(line);
  if (m && !official.has(m[1])) official.set(m[1], m[2].trim());
}
if (official.size < 100) { console.log(text.slice(0, 4000)); throw new Error(`only ${official.size} codes parsed from ${url}: check the parser`); }

const src = readFileSync(join(ROOT, 'scripts/map_bake_city.mjs'), 'utf8');
const table = [...src.matchAll(/^\s+([A-Z]\d{4}): \['(\w+)', '(\w+)'\],\s*\/\/\s*(.*)$/gm)].map(([, code, kind, cls, note]) => ({code, kind, cls, note: note.trim()}));
if (table.length < 30) throw new Error(`only ${table.length} table rows parsed from the baker`);
const inTable = new Set(table.map((t) => t.code));
const drawnMissing = table.filter((t) => t.kind !== 'skip' && !official.has(t.code));
const skippedMissing = table.filter((t) => t.kind === 'skip' && !official.has(t.code));
const relevant = (code) => /^(S1|H[0-9]|K218|K2190)/.test(code);
const uncovered = [...official.keys()].filter((c) => relevant(c) && !inTable.has(c)).sort();
const seen = new Set();
for (const f of readdirSync(join(ROOT, 'public/kit/map/cities')).filter((f) => f.endsWith('.report.json'))) for (const c of Object.keys(JSON.parse(readFileSync(join(ROOT, 'public/kit/map/cities', f), 'utf8')).unmapped)) seen.add(c);

const cell = (s) => String(s).replace(/\|/g, '/');
const md = [
  '# MTFCC table audit', '', `Official list: ${url} (${official.size} codes parsed). Generated by scripts/map_verify_mtfcc.mjs.`, '',
  '| code | baker: kind / class | baker comment | official name |', '|---|---|---|---|',
  ...table.map((t) => `| ${t.code} | ${t.kind} / ${t.cls} | ${cell(t.note)} | ${cell(official.get(t.code) ?? '**not in the official list**')} |`), '',
  `Drawn codes missing from the official list: ${drawnMissing.map((t) => t.code).join(', ') || 'none'}`,
  `Skipped codes missing from the official list (harmless): ${skippedMissing.map((t) => t.code).join(', ') || 'none'}`,
  `Official road/water/park codes missing from the table: ${uncovered.map((c) => `${c} (${official.get(c)})`).join(', ') || 'none'}`, '',
  '## Codes seen in the baked cities but not in the table (not drawn)', '', '| code | official name |', '|---|---|',
  ...[...seen].sort().map((c) => `| ${c} | ${cell(official.get(c) ?? '**not in the official list**')} |`), '',
].join('\n');
writeFileSync(join(ROOT, 'docs/map-verify-mtfcc.md'), md);
console.log(md);
process.exit(drawnMissing.length || uncovered.length ? 1 : 0);
