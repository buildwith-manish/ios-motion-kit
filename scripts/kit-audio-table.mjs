// Writes docs/kit-audio-cues.txt: cue times of the audio demo (resolved + dropped) and the duck curve checkpoints.
//   node scripts/kit-audio-table.mjs
import {build} from 'esbuild';
import {pathToFileURL} from 'node:url';
import {mkdtempSync, rmSync, writeFileSync} from 'node:fs';
import path from 'node:path';

const dir = mkdtempSync(path.join(process.cwd(), 'node_modules', '.kit-table-'));
const out = path.join(dir, 't.mjs');
const kit = path.resolve('src/kit').replace(/\\/g, '/');
await build({
  stdin: {contents: `export * from '${kit}/audio/index'; export {audioDemoCues, FAKE_VO, FAKE_VO_SEGMENTS, AUDIO_DEMO_SECONDS} from '${kit}/demo/AudioDemoCues';`, resolveDir: process.cwd(), loader: 'ts'},
  bundle: true, platform: 'node', format: 'esm', outfile: out, logLevel: 'error', external: ['react', 'react-dom', 'remotion'],
});
const K = await import(pathToFileURL(out).href);
const cues = K.audioDemoCues();
const res = K.resolveCues(cues, {seed: 1});
const lines = [];
lines.push('Kit audio demo - cue times (Kit-Audio-Demo, 10 s, seed 1)');
lines.push('Generated by scripts/kit-audio-table.mjs. "time s" is when the file starts (peak-anchored cues already shifted).');
lines.push('');
lines.push('== 60 fps (1920x1080 or 1080x1920) ==');
lines.push(K.formatCueTable(res, 60));
lines.push('');
lines.push('== frame numbers at 30 fps ==');
lines.push(res.cues.map((c) => `${c.at.toFixed(3)} s -> frame ${Math.round(c.at * 30)}  ${c.name}-${c.variant}`).join('\n'));
lines.push('');
lines.push(`kept ${res.cues.length}, dropped ${res.dropped.length}`);
let maxSim = 0;
for (const c of res.cues) maxSim = Math.max(maxSim, res.cues.filter((y) => y.at <= c.at && y.end > c.at).length);
lines.push(`max simultaneous sounds: ${maxSim}`);
lines.push('');
lines.push('== voice-over (fake) and music duck, depth 7.5 dB, attack 80 ms, release 400 ms, hold 150 ms ==');
lines.push('speech: ' + K.FAKE_VO_SEGMENTS.map(([a, b]) => `${a}-${b} s`).join(', '));
const duck = K.createDuck(K.FAKE_VO, {depthDb: 7.5});
const pts = [0.5, 1.2, 1.28, 2.0, 3.6, 3.75, 4.15, 4.4, 4.48, 6.2, 6.35, 6.75, 7.0, 7.08, 9.0, 9.15, 9.55, 9.9];
lines.push(pts.map((s) => `t=${s.toFixed(2)} s  music ${duck.gainDbAtSeconds(s).toFixed(2)} dB`).join('\n'));
lines.push('');
lines.push('== SFX gain under speech (after duck 6 dB and the 3 dB-under-voice ceiling) ==');
for (const c of res.cues) {
  const mid = c.at + 0.02;
  const g = K.sfxGainAt(c, mid, {voice: K.FAKE_VO});
  lines.push(`${c.at.toFixed(3)} s  ${(c.name + '-' + c.variant).padEnd(18)} cue ${K.gainToDb(c.gain).toFixed(1)} dB -> mix ${K.gainToDb(g).toFixed(1)} dB`);
}
writeFileSync('docs/kit-audio-cues.txt', lines.join('\n') + '\n');
rmSync(dir, {recursive: true, force: true});
console.log(lines.join('\n'));
